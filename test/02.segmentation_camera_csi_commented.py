"""
================================================================================
 02.segmentation_camera_csi_commented.py
 YOLO 实时实例分割 —— 使用 Jetson CSI 摄像头

 功能说明：
   1. 加载 YOLO 分割模型（yolo26n-seg.pt）
   2. 打开 Jetson 开发板的 CSI 摄像头（GStreamer / V4L2 自动回退）
   3. 实时读取视频帧，执行 YOLO 实例分割推理
   4. 将分割结果（mask + 边框 + 类别标签）可视化
   5. 同时将标注后的帧写入 MP4 视频文件，并显示在屏幕上
   6. 按 'q' 键退出程序

 硬件要求：
   - NVIDIA Jetson 系列开发板（Orin / Xavier / Nano 等）
   - CSI 接口摄像头（如 IMX219）

 输出文件：
   /root/yolo26_data/output/02.segmentation_camera_csi.mp4

 原始文件: 02.segmentation_camera_csi.py
================================================================================
"""

import cv2                          # OpenCV 库，用于图像/视频的读取、写入和显示
from ultralytics import YOLO         # Ultralytics YOLO 库，提供目标检测和实例分割功能

# 导入自定义的 CSI 摄像头工具函数
# 该函数封装了 Jetson 平台上的 GStreamer pipeline 和 V4L2 两种打开方式，
# 优先使用 GStreamer（硬件加速），失败时自动回退到 V4L2
from csi_camera_utils import open_jetson_csi_capture

# ============================================================================
# 1. 加载 YOLO 实例分割模型
# ============================================================================
# yolo26n-seg.pt:
#   - 26      → YOLO 版本号
#   - n       → nano（轻量版），适合 Jetson 等边缘设备，速度最快但精度稍低
#   - seg     → segmentation，即实例分割任务（会输出每个目标的像素级 mask）
# 模型路径为绝对路径，存放于 /root/yolo26_data/models/ 目录下
model = YOLO("/root/yolo26_data/models/yolo26n-seg.pt")

# ============================================================================
# 2. 打开 CSI 摄像头
# ============================================================================
# 参数说明：
#   sensor_id  → 摄像头编号，0 表示第一个 CSI 摄像头（CAM0）
#   width      → 采集分辨率的宽度（像素）
#   height     → 采集分辨率的高度（像素）
#   fps        → 目标帧率（Frames Per Second）
#
# 返回值：
#   cap        → cv2.VideoCapture 兼容对象，用法与 cv2.VideoCapture(0) 一致
#   _opened_via→ 字符串，标识实际使用的打开方式（"gstreamer" 或 "v4l2"），
#                 以下划线开头表示该变量在本脚本中未被使用
frame_width = 640
frame_height = 480
fps = 30
cap, _opened_via = open_jetson_csi_capture(
    sensor_id=0,
    width=frame_width,
    height=frame_height,
    fps=fps,
)

# ============================================================================
# 3. 创建视频写入器（VideoWriter），用于保存处理后的视频
# ============================================================================
# fourcc → Four Character Code，指定视频编码格式
#   "mp4v"  → MPEG-4 编码，兼容性好，可在大多数播放器中播放
#   使用 cv2.VideoWriter_fourcc(*"mp4v") 生成 fourcc 码
#
# VideoWriter 参数：
#   output_path → 输出文件的完整路径
#   fourcc      → 编码格式
#   fps         → 输出视频帧率（与输入帧率保持一致）
#   (width, height) → 输出视频分辨率（与输入分辨率保持一致）
output_path = "/root/yolo26_data/output/02.segmentation_camera_csi.mp4"
fourcc = cv2.VideoWriter_fourcc(*"mp4v")
out = cv2.VideoWriter(output_path, fourcc, fps, (frame_width, frame_height))

# ============================================================================
# 4. 主循环：逐帧读取 → YOLO 推理 → 可视化 → 写入文件 → 显示窗口
# ============================================================================
while cap.isOpened():
    # --------------------------------------------------------------------------
    # 4.1 从摄像头读取一帧
    # --------------------------------------------------------------------------
    # success → bool，为 True 表示成功读取到一帧
    # frame   → numpy.ndarray（shape: [height, width, 3]），BGR 格式的彩色图像
    success, frame = cap.read()

    if success:
        # ----------------------------------------------------------------------
        # 4.2 YOLO 实例分割推理
        # ----------------------------------------------------------------------
        # model(frame) 会对输入图像执行前向推理，返回一个 Results 对象的列表
        # （对于单张图片输入，列表长度为 1）
        # 推理结果包含：
        #   - boxes        → 检测到的目标边界框（xyxy 格式，带置信度分数和类别 id）
        #   - masks         → 每个目标的实例分割 mask（像素级二值掩膜）
        #   - keypoints     → 关键点（仅姿态估计模型有，此处为 None）
        #   - probs         → 分类概率（仅分类模型有，此处为 None）
        #   - orig_img      → 输入的原始图像
        results = model(frame)

        # ----------------------------------------------------------------------
        # 4.3 可视化推理结果
        # ----------------------------------------------------------------------
        # results[0].plot() 会在原始图像上叠加：
        #   - 彩色半透明 mask 覆盖在每个检测到的目标区域
        #   - 边界框（颜色按类别区分）
        #   - 类别名称 + 置信度分数标签
        #   返回的是 BGR 格式的 numpy 数组，可直接写入视频或显示
        annotated_frame = results[0].plot()

        # ----------------------------------------------------------------------
        # 4.4 将标注后的帧写入输出视频文件
        # ----------------------------------------------------------------------
        # out.write(annotated_frame)

        # ----------------------------------------------------------------------
        # 4.5 在屏幕窗口中显示标注后的帧
        # ----------------------------------------------------------------------
        # cv2.resize 将图像缩放到 640×480，确保显示窗口大小一致
        # 即使原始图像分辨率变化，窗口也能正常显示
        cv2.imshow("YOLO Inference", cv2.resize(annotated_frame, (640, 480)))

        # ----------------------------------------------------------------------
        # 4.6 键盘检测：按 'q' 键退出循环
        # ----------------------------------------------------------------------
        # cv2.waitKey(1) → 等待 1 毫秒，同时检测是否有键盘输入
        # & 0xFF        → 取低 8 位（兼容 64 位系统上的返回值）
        # ord("q")      → 获取字符 'q' 的 ASCII 码
        if cv2.waitKey(1) & 0xFF == ord("q"):
            break
    else:
        # ----------------------------------------------------------------------
        # 4.7 读取失败则退出循环
        # ----------------------------------------------------------------------
        # 常见原因：摄像头断开、驱动异常、已到达视频文件末尾等
        break

# ============================================================================
# 5. 资源清理：释放摄像头、视频写入器和显示窗口
# ============================================================================
cap.release()           # 释放摄像头资源，停止视频流
out.release()           # 关闭视频写入器，确保输出文件正确保存
cv2.destroyAllWindows() # 关闭所有由 OpenCV 创建的 GUI 窗口
